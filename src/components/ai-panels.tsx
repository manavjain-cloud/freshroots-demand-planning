"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { AlertTriangle, Loader2, RefreshCw, Sparkles } from "lucide-react";
import type { Explanation, PlanningSummary } from "@/lib/ai/explain";
import { cn } from "./ui";

type Stored<T> = { content: T; provider: string; model: string; warnings: string[]; createdAt: string };
type Outcome<T> = { status: "ok"; cached: boolean; data: Stored<T> } | { status: "unavailable"; reason: string; message: string };

function useAi<T>(endpoint: string, body: Record<string, unknown>, autoLoadCached: boolean) {
  const [state, setState] = useState<{ loading: boolean; outcome: Outcome<T> | null }>({ loading: false, outcome: null });
  const key = JSON.stringify(body);
  async function load(opts: { refresh?: boolean; cachedOnly?: boolean } = {}) {
    setState((s) => ({ ...s, loading: true }));
    try {
      const res = await fetch(endpoint, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ ...body, refresh: !!opts.refresh, cachedOnly: !!opts.cachedOnly }) });
      const json = (await res.json()) as Outcome<T> | { status: "none" };
      if ("status" in json && json.status === "none") setState({ loading: false, outcome: null });
      else setState({ loading: false, outcome: json as Outcome<T> });
    } catch {
      setState({ loading: false, outcome: { status: "unavailable", reason: "network", message: "AI explanations are temporarily unavailable (network error). The rule-engine results above are unaffected." } });
    }
  }
  useEffect(() => {
    if (!autoLoadCached) return;
    let cancelled = false;
    (async () => {
      try {
        const res = await fetch(endpoint, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ ...JSON.parse(key), cachedOnly: true }) });
        const json = (await res.json()) as Outcome<T> | { status: "none" };
        if (!cancelled && json.status === "ok") setState({ loading: false, outcome: json as Outcome<T> });
      } catch {
        /* cached load is best-effort */
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [endpoint, key, autoLoadCached]);
  return { ...state, load };
}

function AiShell({ title, children, loading, onGenerate, hasContent, meta }: { title: string; children: React.ReactNode; loading: boolean; onGenerate: (refresh: boolean) => void; hasContent: boolean; meta?: React.ReactNode }) {
  return (
    <section className="rn-card rn-rise overflow-hidden p-0" aria-busy={loading}>
      <div className="flex flex-wrap items-center justify-between gap-2 border-b border-line bg-gradient-to-r from-burgundy/60 to-transparent px-4 py-3">
        <h2 className="flex items-center gap-2 text-sm font-semibold text-ink-1">
          <Sparkles className="size-4 text-accent" aria-hidden /> {title}
        </h2>
        <button type="button" className="rn-btn rn-btn-ghost py-1.5 text-xs" onClick={() => onGenerate(hasContent)} disabled={loading}>
          {loading ? <Loader2 className="size-3.5 animate-spin" aria-hidden /> : hasContent ? <RefreshCw className="size-3.5" aria-hidden /> : <Sparkles className="size-3.5" aria-hidden />}
          {loading ? "Generating…" : hasContent ? "Regenerate" : "Generate"}
        </button>
      </div>
      <div className="space-y-3 p-4 text-sm leading-relaxed text-ink-2">{children}</div>
      {meta ? <div className="border-t border-line px-4 py-2 text-[0.6875rem] text-ink-3">{meta}</div> : null}
    </section>
  );
}

function Unavailable({ message }: { message: string }) {
  return (
    <p className="flex gap-2 rounded-lg border border-warning/30 bg-warning/[0.06] p-3 text-[0.8125rem]" role="status">
      <AlertTriangle className="mt-0.5 size-4 shrink-0 text-warning" aria-hidden />
      <span>{message} The deterministic rule-engine results are unaffected.</span>
    </p>
  );
}

function Warnings({ warnings }: { warnings: string[] }) {
  if (!warnings.length) return null;
  return (
    <ul className="space-y-1 rounded-lg border border-serious/35 bg-serious/[0.06] p-3 text-xs text-[#ffd0bd]">
      {warnings.map((w, i) => (
        <li key={i} className="flex gap-1.5">
          <AlertTriangle className="mt-0.5 size-3.5 shrink-0 text-serious" aria-hidden /> {w}
        </li>
      ))}
    </ul>
  );
}

const List = ({ title, items }: { title: string; items: string[] }) =>
  items.length ? (
    <div>
      <h3 className="mb-1 text-xs font-semibold uppercase tracking-wide text-ink-3">{title}</h3>
      <ul className="list-disc space-y-1 pl-5 marker:text-accent">
        {items.map((x, i) => (
          <li key={i}>{x}</li>
        ))}
      </ul>
    </div>
  ) : null;

const Meta = ({ s }: { s: Stored<unknown> }) => (
  <>
    AI-generated by {s.model} ({s.provider}) on {new Date(s.createdAt).toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })} IST from the rule-engine facts. Explanatory only — it cannot change quantities or classifications and is not a verified business fact.
  </>
);

export function AiExplanationPanel({ recommendationId }: { recommendationId: number }) {
  const { loading, outcome, load } = useAi<Explanation>("/api/ai/explain", { recommendationId }, true);
  const ok = outcome?.status === "ok" ? outcome.data : null;
  return (
    <AiShell title="AI explanation" loading={loading} onGenerate={(refresh) => load({ refresh })} hasContent={!!ok} meta={ok ? <Meta s={ok} /> : "Uses Gemini to translate the calculation into plain language. Optional — the rules work without it."}>
      {outcome?.status === "unavailable" ? <Unavailable message={outcome.message} /> : null}
      {ok ? (
        <>
          <p className="font-medium text-ink-1">{ok.content.headline}</p>
          <p>{ok.content.explanation}</p>
          <List title="Key drivers" items={ok.content.key_drivers} />
          <List title="Planner checks" items={ok.content.planner_checks} />
          <List title="Caveats" items={ok.content.caveats} />
          <Warnings warnings={ok.warnings} />
        </>
      ) : !outcome && !loading ? (
        <p className="text-ink-3">No explanation generated yet for this recommendation.</p>
      ) : null}
      {loading && !ok ? <p className="text-ink-3">Asking Gemini to explain the calculated facts… this can take up to 30 seconds.</p> : null}
    </AiShell>
  );
}

export function AiSummaryPanel({ runId }: { runId: number }) {
  const { loading, outcome, load } = useAi<PlanningSummary>("/api/ai/summary", { runId }, true);
  const ok = outcome?.status === "ok" ? outcome.data : null;
  return (
    <AiShell title={`AI planning summary · run #${runId}`} loading={loading} onGenerate={(refresh) => load({ refresh })} hasContent={!!ok} meta={ok ? <Meta s={ok} /> : "Optional summary of this run for the planner."}>
      {outcome?.status === "unavailable" ? <Unavailable message={outcome.message} /> : null}
      {ok ? (
        <>
          <p className="font-medium text-ink-1">{ok.content.headline}</p>
          <p>{ok.content.summary}</p>
          {ok.content.priority_items.length ? (
            <div>
              <h3 className="mb-1.5 text-xs font-semibold uppercase tracking-wide text-ink-3">Priority items</h3>
              <ul className="space-y-2">
                {ok.content.priority_items.map((p) => (
                  <li key={p.sku_id} className="rounded-lg border border-line bg-white/[0.02] p-2.5">
                    <Link href={`/skus/${encodeURIComponent(p.sku_id)}`} className="font-semibold text-ink-1 underline-offset-2 hover:underline">
                      {p.sku_id}
                    </Link>{" "}
                    — {p.issue}
                    <p className="mt-0.5 text-xs text-ink-3">Check: {p.suggested_check}</p>
                  </li>
                ))}
              </ul>
            </div>
          ) : null}
          {ok.content.exceptions_note ? <p className={cn("text-[0.8125rem]")}>{ok.content.exceptions_note}</p> : null}
          <List title="Data caveats" items={ok.content.data_caveats} />
          <Warnings warnings={ok.warnings} />
        </>
      ) : !outcome && !loading ? (
        <p className="text-ink-3">No summary generated for this run yet.</p>
      ) : null}
      {loading && !ok ? <p className="text-ink-3">Generating a summary from this run&apos;s calculated results… this can take up to 30 seconds.</p> : null}
    </AiShell>
  );
}
